    private void tblCamioneroMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCamioneroMouseClicked
int fila = tblCamionero.getSelectedRow();
        if (fila >= 0) {
            idCamioneroSeleccionado = Integer.parseInt(tblCamionero.getValueAt(fila, 0).toString());
            txtNombre.setText(tblCamionero.getValueAt(fila, 1).toString());
            txtApellidos.setText(tblCamionero.getValueAt(fila, 2).toString());
            txtDireccion.setText(tblCamionero.getValueAt(fila, 3).toString());
            txtSalario.setText(tblCamionero.getValueAt(fila, 4).toString());
            txtDpi.setText(tblCamionero.getValueAt(fila, 5).toString());
            txtTelefono.setText(tblCamionero.getValueAt(fila, 6).toString());
            txtPoblacion.setText(tblCamionero.getValueAt(fila, 7).toString());
        }
    }//GEN-LAST:event_tblCamioneroMouseClicked

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
if (idCamioneroSeleccionado == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un camionero de la tabla.");
        return;
    }
    int confirmacion = JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar este camionero?", "Confirmar", JOptionPane.YES_NO_OPTION);
    if (confirmacion == JOptionPane.YES_OPTION) {
        try {
camioneroDAO.eliminar(idCamioneroSeleccionado);
JOptionPane.showMessageDialog(this, "¡Camionero eliminado correctamente!");
            cargarCamioneros();
            limpiar();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
        }
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
if (idCamioneroSeleccionado == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un camionero de la tabla.");
        return;
    }
    try {
        Camionero c = new Camionero();
        c.setIdCamionero(idCamioneroSeleccionado);
        c.setNombre(txtNombre.getText());
        c.setApellidos(txtApellidos.getText());
        c.setDireccion(txtDireccion.getText());
c.setSalario(new java.math.BigDecimal(txtSalario.getText()));
c.setDpi(txtDpi.getText());
        c.setTelefono(txtTelefono.getText());
        c.setPoblacion(txtPoblacion.getText());
        
        camioneroDAO.actualizar(c);
        
        JOptionPane.showMessageDialog(this, "¡Camionero actualizado correctamente!");
        cargarCamioneros();
        limpiar();
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Ingrese un salario válido (número).");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage());
    }

    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
try {
            Camionero c = new Camionero();
            c.setNombre(txtNombre.getText().trim());
            c.setApellidos(txtApellidos.getText().trim());
            c.setDireccion(txtDireccion.getText().trim());
            c.setSalario(new java.math.BigDecimal(txtSalario.getText().trim()));
            c.setDpi(txtDpi.getText().trim());
            c.setTelefono(txtTelefono.getText().trim());
            c.setPoblacion(txtPoblacion.getText().trim());

            camioneroDAO.insertar(c);

            JOptionPane.showMessageDialog(this, "¡Camionero guardado correctamente!");
            cargarCamioneros();
            limpiar();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese un salario válido (número).");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage());
        }

    }//GEN-LAST:event_btnGuardarActionPerformed

