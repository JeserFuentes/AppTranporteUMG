private void cargarCamioneros() {
        DefaultTableModel modelo = (DefaultTableModel) tblCamionero.getModel();
        modelo.setRowCount(0);
        try {
            List<Camionero> lista = camioneroDAO.listar();
            for (Camionero c : lista) {
                modelo.addRow(new Object[]{
                    c.getIdCamionero(),
                    c.getNombre(),
                    c.getApellidos(),
                    c.getDireccion(),
                    c.getSalario(),
                    c.getDpi(),
                    c.getTelefono(),
                    c.getPoblacion()
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar camioneros: " + e.getMessage());
        }
    }

