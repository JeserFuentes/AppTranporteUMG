private void cargarComboCiudad() {
        try {
            cmbCiudad.removeAllItems();
            List<Ciudad> listaCiudades = ciudadDAO.listar();
            for (Ciudad c : listaCiudades) {
                // Ajustado a los nombres reales de tu clase Ciudad
                cmbCiudad.addItem(c.getCiudad() + " - " + c.getNombre()); 
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar ciudades: " + e.getMessage());
        }
    }

private void cargarTabla() {
        try {
            DefaultTableModel modelo = (DefaultTableModel) tblPaquete.getModel();
            modelo.setRowCount(0); // Limpiar tabla
            List<Paquete> lista = paqueteDAO.listar();
            for (Paquete p : lista) {
                Object[] fila = {
                    p.getIdPaquete(),
                    p.getCodigo(),
                    p.getDescripcion(),
                    p.getDestinatario(),
                    p.getDireccionDestinatario(), 
                    p.getIdCiudad()
                };
                modelo.addRow(fila);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar la tabla: " + e.getMessage());
        }
    }

    private void limpiar() {
        txtCodigo.setText("");
        txtDescripcion.setText("");
        txtDestinatario.setText("");
        txtDireccion.setText("");
        if (cmbCiudad.getItemCount() > 0) {
            cmbCiudad.setSelectedIndex(0);
        }
        idPaqueteSeleccionado = -1;
    }
