    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
try {
            String codigo = txtCodigo.getText().trim();
            String descripcion = txtDescripcion.getText().trim();
            String destinatario = txtDestinatario.getText().trim();
            String direccion = txtDireccion.getText().trim();

            if (codigo.isEmpty() || descripcion.isEmpty() || destinatario.isEmpty() || direccion.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Por favor, complete todos los campos.");
                return;
            }

            String selectedCiudad = cmbCiudad.getSelectedItem().toString();
            int idCiudad = Integer.parseInt(selectedCiudad.split(" - ")[0]);

            Paquete p = new Paquete();
            p.setCodigo(codigo);
            p.setDescripcion(descripcion);
            p.setDestinatario(destinatario);
            p.setDireccionDestinatario(direccion);
            p.setIdCiudad(idCiudad);

            PaqueteDAO paqueteDAO = new PaqueteDAO();
            if (paqueteDAO.insertar(p)) {
                JOptionPane.showMessageDialog(this, "¡Paquete guardado con éxito!");
                cargarTabla();
                limpiar();
            } else {
                JOptionPane.showMessageDialog(this, "Error al guardar el paquete en la BD.");
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
if (idPaqueteSeleccionado == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un paquete de la tabla para actualizar.");
            return;
        }
        try {
            Paquete p = new Paquete();
            p.setIdPaquete(idPaqueteSeleccionado);
            p.setCodigo(txtCodigo.getText().trim());
            p.setDescripcion(txtDescripcion.getText().trim());
            p.setDestinatario(txtDestinatario.getText().trim());
            p.setDireccionDestinatario(txtDireccion.getText().trim());

            String selectedCiudad = cmbCiudad.getSelectedItem().toString();
            p.setIdCiudad(Integer.parseInt(selectedCiudad.split(" - ")[0]));

            PaqueteDAO paqueteDAO = new PaqueteDAO();
            if (paqueteDAO.actualizar(p)) {
                JOptionPane.showMessageDialog(this, "¡Paquete actualizado correctamente!");
                cargarTabla();
                limpiar();
                idPaqueteSeleccionado = -1;
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo actualizar el registro.");
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
if (idPaqueteSeleccionado == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un paquete de la tabla para eliminar.");
            return;
        }
        int confirm = JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar este paquete?", "Confirmar Eliminación", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            try {
                PaqueteDAO paqueteDAO = new PaqueteDAO();
                if (paqueteDAO.eliminar(idPaqueteSeleccionado)) {
                    JOptionPane.showMessageDialog(this, "¡Paquete eliminado!");
                    cargarTabla();
                    limpiar();
                    idPaqueteSeleccionado = -1;
                } else {
                    JOptionPane.showMessageDialog(this, "No se pudo eliminar el registro.");
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblPaqueteMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPaqueteMouseClicked
int fila = tblPaquete.getSelectedRow();
        if (fila >= 0) {
            idPaqueteSeleccionado = Integer.parseInt(tblPaquete.getValueAt(fila, 0).toString());
            txtCodigo.setText(tblPaquete.getValueAt(fila, 1).toString());
            txtDescripcion.setText(tblPaquete.getValueAt(fila, 2).toString());
            txtDestinatario.setText(tblPaquete.getValueAt(fila, 3).toString());
            txtDireccion.setText(tblPaquete.getValueAt(fila, 4).toString());
        }
    }//GEN-LAST:event_tblPaqueteMouseClicked
