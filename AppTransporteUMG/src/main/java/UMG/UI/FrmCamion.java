    private void cargarCamiones() {
        DefaultTableModel modelo = (DefaultTableModel) tblCamion.getModel();
        modelo.setRowCount(0);
        List<Camion> lista = camionDAO.listar();
        for (Camion c : lista) {
            modelo.addRow(new Object[]{
                c.getIdCamion(),
                c.getMatricula(),
                c.getModelo(),
                c.getTipo(),
                c.getPotencia()
            });
        }
    }

