    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            Camion c = new Camion();
            c.setMatricula(txtMatricula.getText().trim());
            c.setModelo(txtModelo.getText().trim());
            c.setPotencia(Integer.parseInt(txtPotencia.getText().trim()));

            // Llamada directa al DAO para insertar
            camionDAO.insertar(c);

            JOptionPane.showMessageDialog(this, "¡Camión guardado correctamente en MySQL!");
            cargarCamiones(); // Recarga la tabla
            limpiar();        // Limpia las cajas de texto

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese un número válido en la potencia.");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al guardar en la base de datos: " + e.getMessage());
        }
    
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
if (idCamionSeleccionado == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un registro de la tabla.");
        return;
    }
    try {
        Camion c = new Camion();
        c.setIdCamion(idCamionSeleccionado);
        c.setMatricula(txtMatricula.getText());
        c.setModelo(txtModelo.getText());
        c.setTipo(txtTipo.getText());
        c.setPotencia(Integer.parseInt(txtPotencia.getText()));
        
        if (camionDAO.actualizar(c)) {
            JOptionPane.showMessageDialog(this, "¡Camión actualizado correctamente en MySQL!");
            cargarCamiones(); // Recarga la tabla con los datos nuevos
            limpiar();         // Limpia las cajas de texto
        } else {
            JOptionPane.showMessageDialog(this, "Error al actualizar el camión.");
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Ingrese un número válido en la potencia.");
    }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
if (idCamionSeleccionado == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un registro de la tabla.");
            return;
        }

        int confirmacion = JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar este camión?", "Confirmar eliminación", JOptionPane.YES_NO_OPTION);
        
        if (confirmacion == JOptionPane.YES_OPTION) {
            if (camionDAO.eliminar(idCamionSeleccionado)) {
                JOptionPane.showMessageDialog(this, "¡Camión eliminado correctamente de MySQL!");
                cargarCamiones(); // Actualiza la tabla
                limpiar();        // Limpia los campos
            } else {
                JOptionPane.showMessageDialog(this, "Error al eliminar el camión.");
            }
        
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblCamionMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCamionMouseClicked
        int fila = tblCamion.getSelectedRow();
        if (fila >= 0) {
            // Ajusta según el orden de tus columnas en la tabla
            idCamionSeleccionado = Integer.parseInt(tblCamion.getValueAt(fila, 0).toString());
            txtMatricula.setText(tblCamion.getValueAt(fila, 1).toString());
            txtModelo.setText(tblCamion.getValueAt(fila, 2).toString());
        }
    }//GEN-LAST:event_tblCamionMouseClicked

