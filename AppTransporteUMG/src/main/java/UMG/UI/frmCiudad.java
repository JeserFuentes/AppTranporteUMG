private void cargarTabla() {
        try {
            DefaultTableModel modelo = (DefaultTableModel) tblCiudad.getModel();
            modelo.setRowCount(0); // Limpiar la tabla antes de cargar
            List<Ciudad> lista = ciudadDAO.listar();
            for (Ciudad c : lista) {
                Object[] fila = {
                    c.getCiudad(),
                    c.getNombre()
                };
                modelo.addRow(fila); // <--- ¡Esto es lo que añade la fila a la tabla visual!
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar la tabla: " + e.getMessage());
        }
    }

    private void limpiar() {
        txtIdCiudad.setText("");
        txtNombreCiudad.setText("");
        idCiudadSeleccionada = -1;
    }
